// Generates dashboard/css/themes.css and dashboard/js/skins.js from dashboard/themes.mjs.
//
// The viewer controls light/dark in three states: an explicit choice sets
// data-theme="light|dark" on <html>, "system" sets nothing. The page adds its
// own override (data-mode) so people can compare both modes side by side.
import { writeFileSync } from 'node:fs';
import { skins, defaultSkin } from '../dashboard/themes.mjs';

const vars = (obj) => Object.entries(obj).map(([k, v]) => `  --${k}: ${v};`).join('\n');
const out = ['/* Generated by scripts/build-themes.mjs. Do not edit by hand. */'];

const d = skins[defaultSkin];
out.push(`:root {\n${vars(d.shape)}\n${vars(d.light)}\n}`);

for (const [id, s] of Object.entries(skins)) {
  const sel = `:root[data-skin="${id}"]`;
  out.push(`${sel} {\n${vars(s.shape)}\n${vars(s.light)}\n  color-scheme: light;\n}`);
  const bare = id === defaultSkin ? ':root:not([data-skin]):not([data-theme="light"]):not([data-mode="light"]),\n  ' : '';
  out.push(
    `@media (prefers-color-scheme: dark) {\n  ${bare}${sel}:not([data-theme="light"]):not([data-mode="light"]) {\n${vars(s.dark).replace(/^/gm, '  ')}\n    color-scheme: dark;\n  }\n}`,
  );
  out.push(`${sel}[data-theme="dark"]:not([data-mode="light"]),\n${sel}[data-mode="dark"] {\n${vars(s.dark)}\n  color-scheme: dark;\n}`);
}

writeFileSync(new URL('../dashboard/css/themes.css', import.meta.url), out.join('\n\n') + '\n');

const meta = Object.fromEntries(
  Object.entries(skins).map(([id, s]) => [id, { name: s.name, blurb: s.blurb, shape: s.shape, light: s.light, dark: s.dark }]),
);
writeFileSync(
  new URL('../dashboard/js/skins.js', import.meta.url),
  `/* Generated by scripts/build-themes.mjs. Do not edit by hand. */\nwindow.CS_SKINS = ${JSON.stringify(meta, null, 2)};\nwindow.CS_DEFAULT_SKIN = ${JSON.stringify(defaultSkin)};\n`,
);
console.log('themes.css + skins.js written for', Object.keys(skins).join(', '));
